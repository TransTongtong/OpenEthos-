  function 夹(x, 低, 高) {
    const a = typeof 低 === 'number' ? 低 : 0;
    const b = typeof 高 === 'number' ? 高 : 1;
    if (typeof x !== 'number' || !isFinite(x)) return a;
    return x < a ? a : (x > b ? b : x);
  }

