  /* 世界状态里的刺激有两种写法：
       { 被骂: true }        —— 一般强度，取默认值
       { 被骂: 0.9 }         —— 明确强度（比如「客户已经在吼了」）
     写死一个数值会让「轻轻一句不满」和「拍桌子」变成同一件事。 */
  function 强(值, 默认) {
    if (值 === true) return 默认;
    if (typeof 值 === 'number' && isFinite(值)) return 夹(值);
    return 0;
  }

